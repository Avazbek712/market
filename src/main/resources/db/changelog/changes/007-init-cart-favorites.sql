--comment: Cart module — one cart per user, hard-deleted line items (no audit value in a removed cart line)

CREATE TABLE cart
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT    NOT NULL,
    active     BOOLEAN   NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT fk_cart_user FOREIGN KEY (user_id)
        REFERENCES users (id)
);

-- Partial unique index, same reasoning as users.email/categories.name: the cart
-- itself is soft-deletable (even though it practically never gets deleted), so a
-- user must be able to get a fresh one later without hitting a dangling UNIQUE.
CREATE UNIQUE INDEX ux_cart_user_active ON cart (user_id) WHERE active = true;

CREATE TABLE cart_items
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id    BIGINT    NOT NULL,
    product_id BIGINT    NOT NULL,
    quantity   INTEGER   NOT NULL,
    active     BOOLEAN   NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT fk_cart_items_cart FOREIGN KEY (cart_id)
        REFERENCES cart (id) ON DELETE CASCADE,
    CONSTRAINT fk_cart_items_product FOREIGN KEY (product_id)
        REFERENCES product (id),
    -- Plain UNIQUE, not partial — cart_items is a hard-delete table on the Java
    -- side (no @SQLDelete/@SQLRestriction), so a removed line is actually gone,
    -- not soft-deleted, and never collides with a re-add.
    CONSTRAINT uq_cart_items_cart_product UNIQUE (cart_id, product_id),
    CONSTRAINT chk_cart_items_quantity_positive CHECK (quantity > 0)
);

